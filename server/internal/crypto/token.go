package crypto

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"encoding/base64"
	"encoding/hex"
	"errors"
	"fmt"
	"os"
)

var ErrMissingKey = errors.New("MULTICA_INTEGRATION_KEY not set")

func key() ([]byte, error) {
	k := os.Getenv("MULTICA_INTEGRATION_KEY")
	if k == "" {
		return nil, ErrMissingKey
	}
	raw, err := hex.DecodeString(k)
	if err != nil || len(raw) != 32 {
		return nil, fmt.Errorf("MULTICA_INTEGRATION_KEY must be 32-byte hex-encoded")
	}
	return raw, nil
}

// EncryptToken returns base64(nonce || ciphertext || tag).
func EncryptToken(plain string) (string, error) {
	k, err := key()
	if err != nil {
		return "", err
	}
	block, err := aes.NewCipher(k)
	if err != nil {
		return "", err
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return "", err
	}
	nonce := make([]byte, gcm.NonceSize())
	if _, err := rand.Read(nonce); err != nil {
		return "", err
	}
	ct := gcm.Seal(nonce, nonce, []byte(plain), nil)
	return base64.StdEncoding.EncodeToString(ct), nil
}

// DecryptToken is the inverse.
func DecryptToken(encoded string) (string, error) {
	k, err := key()
	if err != nil {
		return "", err
	}
	block, err := aes.NewCipher(k)
	if err != nil {
		return "", err
	}
	gcm, err := cipher.NewGCM(block)
	if err != nil {
		return "", err
	}
	raw, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil {
		return "", err
	}
	if len(raw) < gcm.NonceSize() {
		return "", errors.New("ciphertext too short")
	}
	nonce, ct := raw[:gcm.NonceSize()], raw[gcm.NonceSize():]
	plain, err := gcm.Open(nil, nonce, ct, nil)
	if err != nil {
		return "", err
	}
	return string(plain), nil
}
